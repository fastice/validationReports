"""mosaic3d point-mode runs: one -obsDump run per station group.

For each group the master input file is copied with its header replaced by a
small output box around the group's stations (x0 y0 xSize ySize dx dy in km),
and mosaic3d is run with -obsDump on a 'lat lon name' point file. mosaic3d
skips frames that do not overlap the box (getRegion), so each run takes minutes.
The dump is per-observation rows (a_i, d_i, sigma_i, w_i) at the station pixels.
"""
import os
import shutil
import subprocess
import time

import numpy as np
import pandas as pd

from validationreports import gpsSeries

MTOKM = 1000.


def groupDir(cfg, group):
    return os.path.join(cfg['paths']['pointMode'], group['name'])


def dumpPath(cfg, group):
    return os.path.join(groupDir(cfg, group), 'mosaicOffsets.obsDump')


def boxHeader(stationRows, dx, marginKm):
    '''Header line for the group box: x0 y0 xSize ySize dx dy (km).'''
    x = stationRows['x'].to_numpy() / MTOKM
    y = stationRows['y'].to_numpy() / MTOKM
    x0 = np.floor((x.min() - marginKm) / dx) * dx
    y0 = np.floor((y.min() - marginKm) / dx) * dx
    xSize = np.ceil((x.max() + marginKm - x0) / dx) * dx
    ySize = np.ceil((y.max() + marginKm - y0) / dx) * dx
    return f'{x0:.3f} {y0:.3f} {xSize:.3f} {ySize:.3f} {dx} {dx}'


def writeInputs(cfg, group, stations):
    '''Write gpsPoints.txt and the boxed inputFile; returns the group dir.'''
    outDir = groupDir(cfg, group)
    os.makedirs(outDir, exist_ok=True)
    rows = stations[stations['station'].isin(group['stations'])]
    missing = set(group['stations']) - set(rows['station'])
    if missing:
        raise ValueError(f"group {group['name']}: no GPS summary for {sorted(missing)}")
    with open(os.path.join(outDir, 'gpsPoints.txt'), 'w') as fp:
        fp.write(f"# lat lon name -- {cfg['label']} group {group['name']}\n")
        for _, r in rows.iterrows():
            fp.write(f"{r['lat']:.6f} {r['lon']:.6f} {r['station']}\n")
    header = boxHeader(rows, cfg['mosaic3d']['dx'], group.get('marginKm', 5))
    with open(cfg['paths']['masterInput']) as fp:
        lines = fp.readlines()
    #  The output-area line is the first NON-comment line: the NISAR master input
    #  starts with it directly, but the Sentinel-1 one leads with "; Output area".
    #  Blindly replacing lines[0] there left the real area line in place, and
    #  mosaic3d read the second one as projection parameters -- "Could not
    #  determine epgs from rot=0 slat=0".
    iArea = next(i for i, ln in enumerate(lines) if not ln.lstrip().startswith(';'))
    lines[iArea] = header + '\n'
    with open(os.path.join(outDir, 'inputFile'), 'w') as fp:
        fp.writelines(lines)
    return outDir


def mosaic3dCommand(cfg):
    '''Command-line pieces for the point-mode run (list of tokens).'''
    m = cfg['mosaic3d']
    cmd = ['mosaic3d', '-ompThreads', str(m['ompThreads']), '-GTiff',
           '-writeBlank'] + m['flags'].split()
    if m.get('useSquint', False):
        cmd.append('-useSquint')
    if cfg.get('shelfMask'):
        cmd += ['-shelfMask', cfg['shelfMask']]
    cmd += ['-obsDump', 'gpsPoints.txt', '-date1', m['date1'], '-date2', m['date2'],
            'inputFile', cfg['dem'], 'mosaicOffsets']
    return cmd


def dumpIsCurrent(cfg, group):
    '''True when the group's obsDump is newer than the master input.'''
    dump = dumpPath(cfg, group)
    if not os.path.exists(dump):
        return False
    return os.path.getmtime(dump) > os.path.getmtime(cfg['paths']['masterInput'])


def runGroup(cfg, group, stations, force=False, verbose=True):
    '''Run mosaic3d for one group unless its dump is current.'''
    if not force and dumpIsCurrent(cfg, group):
        if verbose:
            print(f"  {group['name']}: obsDump is current, skipping mosaic3d")
        return dumpPath(cfg, group)
    if shutil.which('mosaic3d') is None:
        raise RuntimeError('mosaic3d not found on PATH')
    outDir = writeInputs(cfg, group, stations)
    cmd = mosaic3dCommand(cfg)
    with open(os.path.join(outDir, 'runOff'), 'w') as fp:
        fp.write('# generated by validationreports.pointMode\n')
        fp.write(' '.join(cmd) + '\n')
    if verbose:
        print(f"  {group['name']}: running mosaic3d in {outDir}")
    t0 = time.time()
    with open(os.path.join(outDir, 'run.log'), 'w') as log:
        proc = subprocess.run(cmd, cwd=outDir, stdout=log, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        raise RuntimeError(f"mosaic3d failed for group {group['name']} "
                           f"(see {outDir}/run.log)")
    dump = dumpPath(cfg, group)
    if not os.path.exists(dump):
        raise RuntimeError(f'mosaic3d produced no obsDump for {group["name"]}')
    if verbose:
        print(f"  {group['name']}: done in {(time.time() - t0) / 60:.1f} min")
    return dump


def countRows(dump):
    '''{station: nOBS} for a dump file.'''
    counts = {}
    with open(dump) as fp:
        for line in fp:
            if line.startswith('OBS'):
                name = line.split()[1]
                counts[name] = counts.get(name, 0) + 1
    return counts


def runDumpStage(cfg, force=False, verbose=True):
    '''Run every group; fail loudly if any station has no rows.'''
    stations, _, _ = gpsSeries.loadGpsStage(cfg)
    results = {}
    for group in cfg['groups']:
        dump = runGroup(cfg, group, stations, force=force, verbose=verbose)
        counts = countRows(dump)
        for name in group['stations']:
            n = counts.get(name, 0)
            results[name] = n
            if verbose:
                print(f'    {name}: {n} OBS rows')
    empty = [n for n, c in results.items() if c == 0]
    if empty:
        print(f'WARNING: no observations dumped for {empty}')
    return results
